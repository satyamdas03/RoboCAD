"""OpenFOAM case builder and lightweight runner for RoboCAD Phase 28C.

This adapter turns a surface mesh (``trimesh.Trimesh``) and a boundary-condition
dictionary into a complete OpenFOAM incompressible-flow case.  If OpenFOAM is
available locally (or via Docker when requested) it will run the standard
``blockMesh`` → ``snappyHexMesh`` → ``simpleFoam`` pipeline; otherwise it writes
the case files and returns gracefully.  After a run it parses drag/lift from
``forceCoeffs`` / ``forces`` post-processing files when they exist.
"""
from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

import numpy as np
import trimesh


__all__ = [
    "OpenFOAMCaseResult",
    "build_openfoam_case",
    "run_openfoam_case",
    "parse_force_coefficients",
]


@dataclass
class OpenFOAMCaseResult:
    """Result object returned by the OpenFOAM adapter."""

    success: bool = False
    case_dir: Optional[Path] = None
    files_written: list[str] = field(default_factory=list)
    openfoam_detected: bool = False
    run_success: Optional[bool] = None
    coefficients: dict[str, Any] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)
    details: dict[str, Any] = field(default_factory=dict)

    def model_dump(self) -> dict[str, Any]:
        return {
            "success": self.success,
            "case_dir": str(self.case_dir) if self.case_dir else None,
            "files_written": self.files_written,
            "openfoam_detected": self.openfoam_detected,
            "run_success": self.run_success,
            "coefficients": self.coefficients,
            "errors": self.errors,
            "details": self.details,
        }


def _foam_header(object_name: str, class_name: str) -> str:
    return f"""/* OpenFOAM file generated by RoboCAD Phase 28C */
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {class_name};
    object      {object_name};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //"""


def _format_uniform(value: Any) -> str:
    if isinstance(value, (list, tuple, np.ndarray)):
        vals = []
        for v in value:
            f = float(v)
            if abs(f) < 1e-9:
                f = 0.0
            vals.append(str(round(f, 9)))
        return f"uniform ({' '.join(vals)})"
    return f"uniform {float(value)}"


def _write_block_mesh_dict(
    path: Path,
    bounds: tuple[tuple[float, float, float], tuple[float, float, float]],
    cells: tuple[int, int, int] = (30, 30, 30),
) -> None:
    """Write a hex background mesh that encloses the surface bounding box."""
    (xmin, ymin, zmin), (xmax, ymax, zmax) = bounds
    vertices = [
        (xmin, ymin, zmin),  # 0
        (xmax, ymin, zmin),  # 1
        (xmax, ymax, zmin),  # 2
        (xmin, ymax, zmin),  # 3
        (xmin, ymin, zmax),  # 4
        (xmax, ymin, zmax),  # 5
        (xmax, ymax, zmax),  # 6
        (xmin, ymax, zmax),  # 7
    ]
    verts_str = "\n".join(f"        ( {x} {y} {z} )" for x, y, z in vertices)
    nx, ny, nz = cells

    content = f"""{_foam_header("blockMeshDict", "dictionary")}

convertToMeters 1.0;

vertices
(
{verts_str}
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1)
);

edges
(
);

boundary
(
    inlet
    {{
        type patch;
        faces
        (
            (0 4 7 3)
        );
    }}
    outlet
    {{
        type patch;
        faces
        (
            (1 2 6 5)
        );
    }}
    bottom
    {{
        type patch;
        faces
        (
            (0 1 5 4)
        );
    }}
    top
    {{
        type patch;
        faces
        (
            (3 7 6 2)
        );
    }}
    front
    {{
        type patch;
        faces
        (
            (0 3 2 1)
        );
    }}
    back
    {{
        type patch;
        faces
        (
            (4 5 6 7)
        );
    }}
);

mergePatchPairs
(
);

// ************************************************************************* //"""
    path.write_text(content + "\n", encoding="utf-8")


