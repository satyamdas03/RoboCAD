def _write_field_file(
    path: Path,
    field: str,
    class_name: str,
    dimensions: list[int],
    internal_value: Any,
    boundary_conditions: dict[str, dict[str, Any]],
) -> None:
    lines = [_foam_header(field, class_name), ""]
    lines.append("dimensions")
    lines.append(f"    ({' '.join(str(d) for d in dimensions)});")
    lines.append("")
    lines.append("internalField")
    lines.append(f"    {_format_uniform(internal_value)};")
    lines.append("")
    lines.append("boundaryField")
    lines.append("(")
    for patch, spec in boundary_conditions.items():
        field_spec = spec.get(field, {})
        ptype = field_spec.get("type", "zeroGradient")
        lines.append(f"    {patch}")
        lines.append("    {")
        lines.append(f"        type {ptype};")
        if "value" in field_spec:
            lines.append(f"        value {_format_uniform(field_spec['value'])};")
        lines.append("    }")
    lines.append(");")
    lines.append("")
    lines.append("// ************************************************************************* //")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_control_dict(
    path: Path,
    solver: str,
    reference_values: dict[str, float],
    write_force_coeffs: bool,
) -> None:
    flow_velocity = reference_values.get("flow_velocity_ms", 10.0)
    l_ref = reference_values.get("characteristic_length_m", 1.0)
    a_ref = reference_values.get("reference_area_m2", l_ref * l_ref)
    rho = reference_values.get("density_kg_m3", 1.225)

    functions = ""
    if write_force_coeffs:
        functions = f"""
functions
{{
    forceCoeffs
    {{
        type            forceCoeffs;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   10;
        log             true;
        patches         (model);
        rhoInf          {rho};
        CofR            (0 0 0);
        liftDir         (0 0 1);
        dragDir         (1 0 0);
        pitchAxis       (0 1 0);
        magUInf         {flow_velocity};
        lRef            {l_ref};
        Aref            {a_ref};
    }}

    forces
    {{
        type            forces;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   10;
        log             true;
        patches         (model);
        rhoInf          {rho};
        CofR            (0 0 0);
    }}
}}
"""

    content = f"""{_foam_header("controlDict", "dictionary")}

application     {solver};

startFrom       startTime;

startTime       0;

stopAt          endTime;

endTime         500;

deltaT          1;

writeControl    timeStep;

writeInterval   100;

purgeWrite      2;

writeFormat     ascii;

writePrecision  6;

writeCompression off;

timeFormat      general;

timePrecision   6;

runTimeModifiable true;
{functions}
// ************************************************************************* //"""
    path.write_text(content + "\n", encoding="utf-8")


