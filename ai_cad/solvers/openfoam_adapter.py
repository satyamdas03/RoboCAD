def parse_force_coefficients(case_dir: Path | str) -> dict[str, Any]:
    """Parse the latest drag/lift values from OpenFOAM post-processing.

    Searches ``postProcessing/forceCoeffs/0/forceCoeffs.dat`` and
    ``postProcessing/forces/0/forces.dat`` and returns the last row values.
    """
    case_dir = Path(case_dir)
    coefficients: dict[str, Any] = {}

    candidates = [
        (case_dir / "postProcessing" / "forceCoeffs" / "0" / "forceCoeffs.dat"),
        (case_dir / "postProcessing" / "forces" / "0" / "forces.dat"),
    ]

    for dat_file in candidates:
        if not dat_file.exists():
            continue
        try:
            text = dat_file.read_text(encoding="utf-8")
        except Exception:
            continue

        lines = [ln.strip() for ln in text.splitlines()]
        header: Optional[list[str]] = None
        data_lines: list[list[str]] = []
        for ln in lines:
            if not ln:
                continue
            if ln.startswith("#"):
                # First comment line is the column header.
                if header is None:
                    header = ln.lstrip("#").split()
                continue
            data_lines.append(ln.split())

        if not data_lines:
            continue

        latest = data_lines[-1]
        if header and len(header) == len(latest):
            for key, raw in zip(header, latest):
                try:
                    coefficients[key] = float(raw)
                except ValueError:
                    coefficients[key] = raw
        elif len(latest) >= 3:
            # Default fallback: time, Cd, Cl.
            try:
                coefficients.setdefault("time", float(latest[0]))
                coefficients.setdefault("Cd", float(latest[1]))
                coefficients.setdefault("Cl", float(latest[2]))
            except ValueError:
                pass

    return coefficients
