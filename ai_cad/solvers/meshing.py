def write_openfoam_case_dir(
    shape_or_mesh: Any,
    output_dir: Path | str,
    mesh_filename: str = "surface_mesh.stl",
) -> MeshResult:
    """Generate an OpenFOAM case directory with ``blockMesh`` / ``snappyHexMesh`` stubs.

    Exports the input surface mesh as an STL into the case directory, then writes
    the required OpenFOAM dictionary files. This does not run any OpenFOAM
    binaries; it produces a simulation-ready starting point.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    errors: list[str] = []

    surface_mesh, input_errors = _surface_mesh_from_input(shape_or_mesh)
    if surface_mesh is None:
        return MeshResult(
            success=False,
            errors=input_errors,
            details={"stage": "input_validation"},
        )

    surface_mesh.fix_normals()
    surface_mesh.merge_vertices()
    stl_path = output_dir / mesh_filename
    try:
        surface_mesh.export(str(stl_path))
    except Exception as exc:
        errors.append(f"Failed to export surface STL: {exc}")

    system_dir = output_dir / "system"
    constant_dir = output_dir / "constant"
    polymesh_dir = constant_dir / "polyMesh"
    zero_dir = output_dir / "0"
    for d in (system_dir, constant_dir, polymesh_dir, zero_dir):
        d.mkdir(parents=True, exist_ok=True)

    try:
        _write_openfoam_blockmesh_dict(system_dir / "blockMeshDict", mesh_filename)
        _write_openfoam_snappy_dict(system_dir / "snappyHexMeshDict", mesh_filename)
    except Exception as exc:
        errors.append(f"Failed to write OpenFOAM dictionaries: {exc}")

    try:
        readme = [
            "# OpenFOAM case directory generated by RoboCAD Phase 28C",
            "",
            f"Surface mesh: {mesh_filename}",
            "",
            "Suggested pipeline:",
            "  blockMesh",
            "  snappyHexMesh",
            "  simpleFoam (or your chosen solver)",
            "",
            "Use ``ai_cad.solvers.meshing.tetrahedral_mesh`` to generate a true",
            "tetrahedral volume mesh with Gmsh or Netgen if installed.",
        ]
        (output_dir / "README.md").write_text("\n".join(readme) + "\n", encoding="utf-8")
    except Exception as exc:
        errors.append(f"Failed to write README: {exc}")

    success = len(errors) == 0 and stl_path.exists()
    return MeshResult(
        success=success,
        mesh_path=stl_path if stl_path.exists() else None,
        format="stl_surface",
        solver_case_path=output_dir,
        solver="openfoam_stub",
        errors=errors,
        details={
            "surface_vertices": len(surface_mesh.vertices),
            "surface_faces": len(surface_mesh.faces),
        },
    )


def tet_mesh_with_gmsh(
    shape_or_mesh: Any,
    output_dir: Path | str,
    mesh_size: float = 0.1,
) -> MeshResult:
    """Attempt tetrahedral meshing with Gmsh.

    If Gmsh is not importable, returns a graceful error result.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    surface_mesh, input_errors = _surface_mesh_from_input(shape_or_mesh)
    if surface_mesh is None:
        return MeshResult(
            success=False,
            format="msh",
            errors=input_errors,
            details={"stage": "input_validation"},
        )

    try:
        import gmsh
    except ImportError as exc:
        return MeshResult(
            success=False,
            format="msh",
            errors=[f"Gmsh not installed: {exc}"],
            details={"tool": "gmsh", "available": False},
        )

    stl_path = output_dir / "surface_for_gmsh.stl"
    surface_mesh.export(str(stl_path))
    mesh_path = output_dir / "volume_mesh.msh"

    try:
        gmsh.initialize()
        gmsh.model.add("robocad_volume")
        gmsh.merge(str(stl_path))
        gmsh.model.geo.synchronize()

        surfaces = gmsh.model.getEntities(2)
        if surfaces:
            surface_loop = gmsh.model.geo.addSurfaceLoop([s[1] for s in surfaces])
            gmsh.model.geo.addVolume([surface_loop])
            gmsh.model.geo.synchronize()

        gmsh.option.setNumber("Mesh.CharacteristicLengthMin", mesh_size * 0.1)
        gmsh.option.setNumber("Mesh.CharacteristicLengthMax", mesh_size)
        gmsh.model.mesh.generate(2)
        gmsh.model.mesh.generate(3)
        gmsh.write(str(mesh_path))
        gmsh.finalize()

        return MeshResult(
            success=True,
            mesh_path=mesh_path,
            format="msh",
            errors=[],
            details={
                "tool": "gmsh",
                "available": True,
                "surface_vertices": len(surface_mesh.vertices),
                "surface_faces": len(surface_mesh.faces),
            },
        )
    except Exception as exc:
        try:
            gmsh.finalize()
        except Exception:
            pass
        return MeshResult(
            success=False,
            format="msh",
            errors=[f"Gmsh meshing failed: {exc}"],
            details={"tool": "gmsh", "available": True},
        )


def tet_mesh_with_netgen(
    shape_or_mesh: Any,
    output_dir: Path | str,
    mesh_size: float = 0.1,
) -> MeshResult:
    """Attempt tetrahedral meshing with Netgen.

    If Netgen is not importable, returns a graceful error result.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    surface_mesh, input_errors = _surface_mesh_from_input(shape_or_mesh)
    if surface_mesh is None:
        return MeshResult(
            success=False,
            format="vol",
            errors=input_errors,
            details={"stage": "input_validation"},
        )

    try:
        import netgen
        from netgen.meshing import MeshingParameters
        import netgen.occ  # noqa: F401
    except ImportError as exc:
        return MeshResult(
            success=False,
            format="vol",
            errors=[f"Netgen not installed: {exc}"],
            details={"tool": "netgen", "available": False},
        )

    stl_path = output_dir / "surface_for_netgen.stl"
    surface_mesh.export(str(stl_path))
    mesh_path = output_dir / "volume_mesh.vol"

    try:
        geo = netgen.occ.OCCGeometry(str(stl_path))
        mp = MeshingParameters(maxh=mesh_size)
        ng_mesh = geo.GenerateMesh(mp=mp)
        ng_mesh.Save(str(mesh_path))

        return MeshResult(
            success=True,
            mesh_path=mesh_path,
            format="vol",
            errors=[],
            details={
                "tool": "netgen",
                "available": True,
                "surface_vertices": len(surface_mesh.vertices),
                "surface_faces": len(surface_mesh.faces),
            },
        )
    except Exception as exc:
        return MeshResult(
            success=False,
            format="vol",
            errors=[f"Netgen meshing failed: {exc}"],
            details={"tool": "netgen", "available": True},
        )


def tetrahedral_mesh(
    shape_or_mesh: Any,
    output_dir: Path | str,
    mesh_size: float = 0.1,
    prefer: str = "gmsh",
) -> MeshResult:
    """Generate a tetrahedral volume mesh using Gmsh or Netgen.

    Falls back from the preferred mesher to the other when the first is missing
    or fails. If neither is available, returns an error ``MeshResult`` with the
    collected messages.
    """
    if prefer not in ("gmsh", "netgen"):
        return MeshResult(
            success=False,
            errors=[f"Invalid preferred mesher: {prefer}. Choose 'gmsh' or 'netgen'."],
            details={"stage": "configuration"},
        )

    order = ["gmsh", "netgen"] if prefer == "gmsh" else ["netgen", "gmsh"]
    results: list[MeshResult] = []
    for tool in order:
        if tool == "gmsh":
            res = tet_mesh_with_gmsh(shape_or_mesh, output_dir, mesh_size)
        else:
            res = tet_mesh_with_netgen(shape_or_mesh, output_dir, mesh_size)
        if res.success:
            return res
        results.append(res)

    errors = [f"{r.details.get('tool', 'tool')}: {r.errors[0]}" for r in results if r.errors]
    return MeshResult(
        success=False,
        errors=errors,
        details={"attempted": order, "fallback_exhausted": True},
    )


