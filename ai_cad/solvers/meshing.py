def gmsh_available() -> bool:
    """Return True if the Gmsh Python module can be imported."""
    try:
        import gmsh  # noqa: F401
        return True
    except Exception:
        return False


def netgen_available() -> bool:
    """Return True if Netgen Python bindings are available."""
    try:
        import netgen  # noqa: F401
        return True
    except Exception:
        return False


def mesh_info(mesh: trimesh.Trimesh) -> dict[str, Any]:
    """Return a summary dict useful for solver input files."""
    return {
        "vertices": len(mesh.vertices),
        "faces": len(mesh.faces),
        "volume_m3": float(mesh.volume) / 1e9 if mesh.is_watertight else 0.0,
        "bounds_m": mesh.bounds.tolist(),
        "watertight": mesh.is_watertight,
        "is_winding_consistent": mesh.is_winding_consistent,
    }


def write_vtk_mesh(mesh: trimesh.Trimesh, path: Path) -> None:
    """Write a surface mesh to a legacy VTK file for external solvers."""
    with path.open("w", encoding="utf-8") as f:
        f.write("# vtk DataFile Version 3.0\n")
        f.write("RoboCAD surface mesh\n")
        f.write("ASCII\n")
        f.write("DATASET POLYDATA\n")
        f.write(f"POINTS {len(mesh.vertices)} float\n")
        for v in mesh.vertices:
            f.write(f"{v[0]} {v[1]} {v[2]}\n")
        f.write(f"POLYGONS {len(mesh.faces)} {len(mesh.faces) * 4}\n")
        for face in mesh.faces:
            f.write(f"3 {face[0]} {face[1]} {face[2]}\n")


def coarse_tet_mesh(mesh: trimesh.Trimesh) -> dict[str, Any]:
    """Return a minimal fallback tetrahedral mesh from a watertight surface.

    When Gmsh/Netgen are unavailable this approximates the volume with the
    convex hull tetrahedralization from scipy.spatial.Delaunay. The result is
    not boundary-conforming for concave shapes but is enough for integration
    tests and solver file format validation.
    """
    try:
        from scipy.spatial import Delaunay
    except Exception as exc:
        raise RuntimeError("scipy is required for fallback tetrahedral meshing") from exc

    pts = mesh.vertices
    hull = Delaunay(pts)
    return {
        "vertices": hull.points.tolist(),
        "tetrahedra": hull.simplices.tolist(),
        "element_count": len(hull.simplices),
    }


def generate_volume_mesh(
    mesh: trimesh.Trimesh,
    output_dir: Path,
    target_edge_length: float = 1.0,
) -> dict[str, Any]:
    """Generate a volume mesh, preferring Gmsh if available.

    Returns a dict with file paths and mesh statistics. External mesher errors
    fall back to the coarse tetrahedralization.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    surface_vtk = output_dir / "surface.vtk"
    write_vtk_mesh(mesh, surface_vtk)

    if gmsh_available():
        try:
            return _gmsh_tet_mesh(mesh, output_dir, target_edge_length)
        except Exception as exc:
            return {"error": str(exc), "fallback": True, **coarse_tet_mesh(mesh)}

    return {
        "surface_vtk": str(surface_vtk),
        **coarse_tet_mesh(mesh),
    }


def _gmsh_tet_mesh(
    mesh: trimesh.Trimesh,
    output_dir: Path,
    target_edge_length: float,
) -> dict[str, Any]:
    import gmsh

    gmsh.initialize()
    try:
        gmsh.model.add("robocad")
        tags = []
        for v in mesh.vertices:
            tags.append(gmsh.model.geo.addPoint(v[0], v[1], v[2], target_edge_length))
        # Simplified: gmsh requires a full surface/volume definition; this is a
        # placeholder that at least exercises the API without crashing.
        gmsh.model.geo.synchronize()
        gmsh.model.mesh.generate(3)
        msh_path = output_dir / "volume.msh"
        gmsh.write(str(msh_path))
        _, _, elem_tags = gmsh.model.mesh.getElements(dim=3)
        return {
            "surface_vtk": str(output_dir / "surface.vtk"),
            "volume_msh": str(msh_path),
            "element_count": sum(len(t) for t in elem_tags),
        }
    finally:
        gmsh.finalize()
