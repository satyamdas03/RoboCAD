"""Volume meshing layer for the RoboCAD deep solver pipeline (Phase 28C).

Wraps optional Gmsh / Netgen tetrahedral meshers, writes OpenFOAM
``blockMesh`` / ``snappyHexMesh`` case-directory stubs, and keeps the Phase 28A
compatibility helpers ``generate_volume_mesh`` and ``write_vtk_mesh`` used by
the solver adapters.

Real solver tools are optional; when missing, the layer returns a
``MeshResult`` with a clear error, while the adapter-level fallback path still
produces a coarse tetrahedralization.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

import numpy as np
import trimesh


try:
    from build123d import Shape
except Exception:  # pragma: no cover
    Shape = None  # type: ignore[misc,assignment]


# ---------------------------------------------------------------------------
# Phase 28C result dataclass
# ---------------------------------------------------------------------------


@dataclass
class MeshResult:
    """Result of a volume meshing pass."""

    success: bool
    mesh_path: Optional[Path] = None
    format: str = ""
    solver_case_path: Optional[Path] = None
    solver: str = ""
    errors: list[str] = field(default_factory=list)
    details: dict[str, Any] = field(default_factory=dict)

    def model_dump(self) -> dict[str, Any]:
        return {
            "success": self.success,
            "mesh_path": str(self.mesh_path) if self.mesh_path else None,
            "format": self.format,
            "solver_case_path": str(self.solver_case_path) if self.solver_case_path else None,
            "solver": self.solver,
            "errors": self.errors,
            "details": self.details,
        }


# ---------------------------------------------------------------------------
# Phase 28C helpers
# ---------------------------------------------------------------------------


def _surface_mesh_from_input(shape_or_mesh: Any) -> tuple[Optional[trimesh.Trimesh], list[str]]:
    """Normalize a build123d Shape or trimesh.Trimesh into a surface mesh."""
    if isinstance(shape_or_mesh, trimesh.Trimesh):
        return shape_or_mesh, []

    if Shape is not None and isinstance(shape_or_mesh, Shape):
        try:
            raw_vertices, raw_faces = shape_or_mesh.tessellate(0.01)
            verts = np.array(
                [[float(v.X), float(v.Y), float(v.Z)] for v in raw_vertices],
                dtype=float,
            )
            faces = np.asarray(raw_faces, dtype=int)
            mesh = trimesh.Trimesh(vertices=verts, faces=faces, process=True)
            mesh.fix_normals()
            mesh.merge_vertices()
            return mesh, []
        except Exception as exc:
            return None, [f"Failed to tessellate shape: {exc}"]

    return None, [f"Unsupported input type: {type(shape_or_mesh)}"]


